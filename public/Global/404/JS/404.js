function goBack(event) {
    /*
    =====================================================
    PREVENT DEFAULT LINK BEHAVIOR
    =====================================================
    */

    if (event) {
        event.preventDefault();
    }

    /*
    =====================================================
    CHECK BROWSER HISTORY
    =====================================================
    */

    if (window.history.length > 1) {
        window.history.back();
        return;
    }

    /*
    =====================================================
    FALLBACK TO MAIN MENU
    =====================================================
    */

    window.location.href = "/";
}